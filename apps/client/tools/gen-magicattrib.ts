/**
 * Blue-item magic lines (TB6) from the original table, for the Thợ rèn forge and later for random blue drops.
 *
 *   npm run gen:magic -w @vltk/client
 *
 * Source: data_extract `\settings\item\magicattrib.txt` (330 rows; the copies in item/000–003 differ only in weights).
 * Columns: 0 prefix/suffix name (Chinese, unused), 1 是否前缀 (1 = prefix: no ngũ hành; 0 = suffix: needs the item's
 * ngũ hành, column 2), 3 magic level (1–10; an item of level L takes rows of level ≤ L), 4 attribute id, 5–10 three
 * parameters (min, max), 11 Chinese note, 12–22 weight per item kind (0 = never on that kind):
 * melee, range, armor, ring, amulet, boot, belt, helm, cuff, pendant, horse.
 * In the original tooltips (and the SHXT screenshots) prefixes are the always-on lines and suffixes the hidden lines
 * of the item's ngũ hành (BACKLOG TB7).
 * Output: packages/shared/src/items/magicattrib.gen.ts
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CLIENT_ROOT, readTable } from './jx/source.ts';
import { VERIFIED_MAX, readMagicAttribNames } from './jx/magicattr.ts';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '../../../packages/shared/src/items/magicattrib.gen.ts');
const KINDS = ['melee', 'range', 'armor', 'ring', 'amulet', 'boot', 'belt', 'helm', 'cuff', 'pendant', 'horse'];

const names = readMagicAttribNames(CLIENT_ROOT);
const { rows } = readTable('\\settings\\item\\magicattrib.txt');
const out: unknown[] = [];
const num = (s: string | undefined) => { const n = parseInt(s?.trim() ?? '', 10); return Number.isFinite(n) ? n : 0; };
rows.forEach((r, i) => {
  const id = num(r[4]);
  if (!r[0]?.trim() || !id) return;
  const kinds = KINDS.filter((_, k) => num(r[12 + k]) > 0);
  // Weight per kind = chance per million that the row enters a position's candidate list (docs/research/luck-drops.md).
  const weights = Object.fromEntries(KINDS.map((k, i) => [k, num(r[12 + i])]).filter(([, w]) => (w as number) > 0));
  if (!kinds.length) return; // never rolled on anything
  const name = id <= VERIFIED_MAX && names[id] ? names[id] : `attr${id}`;
  const prefix = num(r[1]) === 1;
  out.push({
    row: i + 1, attr: name, prefix, series: prefix || r[2]?.trim() === '' ? -1 : num(r[2]), level: num(r[3]),
    min: num(r[5]), max: num(r[6]), kinds, weights,
  });
});

const ts = `// Generated by apps/client/tools/gen-magicattrib.ts from settings/item/magicattrib.txt. Do not edit by hand.
/* eslint-disable */
import type { ItemKind } from './items.js';

/** One row of the original blue-line table. */
export interface MagicAttribRow {
  /** Row number in the table (1 = first data row). */
  row: number;
  /** Magic attribute name (magicdesc.ini key). */
  attr: string;
  /** Prefix = always-on line; suffix = hidden line of the item's ngũ hành. */
  prefix: boolean;
  /** Ngũ hành a suffix needs (0 Kim, 1 Mộc, 2 Thủy, 3 Hỏa, 4 Thổ); -1 = any. */
  series: number;
  /** Magic level 1–10: on items of this level or higher. */
  level: number;
  /** First parameter (the value of the line). */
  min: number;
  max: number;
  /** Item kinds the row can be rolled on. */
  kinds: ItemKind[];
  /**
   * Weight per kind (columns 12–22): the row joins a position's candidates when weight > rand(1 000 000) / luck factor
   * (formulas/drops.ts; docs/research/luck-drops.md: 2 = +all skills "2 per million", 1000 = luck line "1/1000").
   */
  weights: Partial<Record<ItemKind, number>>;
}

export const MAGIC_ATTRIBS: MagicAttribRow[] = [
${out.map(o => `  ${JSON.stringify(o)},`).join('\n')}
];
`;
fs.writeFileSync(OUT, ts);
console.log(`magicattrib.gen.ts: ${out.length} rows`);
