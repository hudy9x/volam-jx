/**
 * Character tables of the original client -> packages/shared/src/characters/player.gen.ts.
 *
 *   npm run gen:player -w @vltk/client
 *
 * Sources (data_extract; read only):
 *   settings/npc/player/level_exp.txt          exp needed to leave each level (1–200)
 *   settings/npc/player/level_add.txt          per ngũ hành: Sinh lực / Nội lực / Thể lực per level and per point, base resists
 *   settings/npc/player/newplayerini00–09.ini  new character per hệ × giới (file = hệ × 2 + giới): potentials, start skills
 *   settings/npc/player/basevalue.ini          run / walk speed, attack / cast / hurt frames
 * Formulas using them: packages/shared/src/formulas/ (docs/formulas/README.md).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readGameFile, readTable } from './jx/source.ts';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '../../../packages/shared/src/characters/player.gen.ts');
const DIR = '\\settings\\npc\\player\\';
const SERIES = ['kim', 'moc', 'thuy', 'hoa', 'tho'] as const;

/** [section] key=value of a GBK ini. */
function ini(file: string): Record<string, Record<string, string>> {
  const out: Record<string, Record<string, string>> = {};
  let sec = '';
  for (const raw of new TextDecoder('gbk').decode(readGameFile(DIR + file)).split(/\r?\n/)) {
    const line = raw.trim();
    const m = /^\[(.+)\]$/.exec(line);
    if (m) { sec = m[1]; out[sec] = {}; continue; }
    const eq = line.indexOf('=');
    if (eq > 0 && sec) out[sec][line.slice(0, eq).trim()] = line.slice(eq + 1).trim();
  }
  return out;
}

// exp to leave level L (index L - 1)
const exp = readTable(DIR + 'level_exp.txt').rows.filter(r => Number(r[0]) >= 1).map(r => Number(r[1]) || 0);

const add = readTable(DIR + 'level_add.txt');
const col = (name: string) => add.header.indexOf(name);
const levelAdd = Object.fromEntries(add.rows.slice(0, 5).map((r, i) => {
  const n = (name: string) => Number(r[col(name)]) || 0;
  return [SERIES[i], {
    lifePerLevel: n('LifePerLevel'), lifePerVitality: n('LifePerVitality'),
    manaPerLevel: n('ManaPerLevel'), manaPerEnergy: n('ManaPerEnergy'),
    staminaPerLevel: [n('StaminaMalePerLevel'), n('StaminaFemalePerLevel')], staminaBase: [n('StaminaMaleBase'), n('StaminaFemaleBase')],
    leadExpShare: n('LeadExpShare'),
    resist: { fire: n('fireres'), cold: n('coldres'), poison: n('poisonres'), light: n('lightingres'), phys: n('physicres') },
  }];
}));

// One row per hệ: in 4 of 5 hệ the male and female files are identical; newplayerini01 (Kim, female) is a leftover
// (potentials 30/20/25/10 = 85 instead of 100, one start skill, Sinh lực 100), so the male row is used for both sexes.
const newPlayer: Record<string, unknown> = {};
for (let i = 0; i < 10; i += 2) {
  const f = ini(`newplayerini0${i}.ini`);
  const role = f.ROLE, sk = f.FSKILLS ?? {};
  const skills: [number, number][] = [];
  for (let k = 1; k <= Number(sk.COUNT ?? 0); k++) skills.push([Number(sk[`S${k}`]), Number(sk[`L${k}`]) || 1]);
  const series = SERIES[Number(role.ifiveprop)], sex = Number(role.bsex);
  void sex;
  newPlayer[series] = {
    str: Number(role.ipower), dex: Number(role.iagility), vit: Number(role.iouter), eng: Number(role.iinside), luck: Number(role.iluck),
    skills,
  };
}

const bv = ini('basevalue.ini');
const base = {
  runSpeed: Number(bv.Common.RunSpeed), walkSpeed: Number(bv.Common.WalkSpeed),
  attackFrames: Number(bv.Common.AttackFrame), castFrames: Number(bv.Common.CastFrame), hurtFrames: Number(bv.Common.HurtFrame),
};

const ts = `// Generated by apps/client/tools/gen-player.ts from settings/npc/player/*. Do not edit by hand.
/* eslint-disable */
import type { Element } from './factions.js';

/** Exp needed to leave level L: LEVEL_EXP[L - 1] (level_exp.txt; 200 = max level). */
export const LEVEL_EXP: number[] = ${JSON.stringify(exp)};

export interface LevelAdd {
  lifePerLevel: number; lifePerVitality: number; manaPerLevel: number; manaPerEnergy: number;
  /** [male, female]. */
  staminaPerLevel: [number, number]; staminaBase: [number, number];
  /** % of team exp the leader gets as leadership exp. */
  leadExpShare: number;
  /** Base resists (%) of the hệ. */
  resist: { fire: number; cold: number; poison: number; light: number; phys: number };
}
/** Per ngũ hành (level_add.txt). */
export const LEVEL_ADD: Record<Element, LevelAdd> = ${JSON.stringify(levelAdd)};

export interface NewPlayer {
  /** Sức mạnh, Thân pháp, Sinh khí, Nội công, May mắn of a new character. */
  str: number; dex: number; vit: number; eng: number; luck: number;
  /** Skills a new character knows: [skill id, level]. */
  skills: [number, number][];
}
/** New character per hệ, both sexes (newplayerini<hệ × 2>.ini; the female files are identical except a broken Kim one). */
export const NEW_PLAYER: Record<Element, NewPlayer> = ${JSON.stringify(newPlayer)};

/** basevalue.ini: speeds in original map units per game loop, action lengths in game loops (18 per second). */
export const PLAYER_BASE = ${JSON.stringify(base)} as const;
`;
fs.writeFileSync(OUT, ts);
console.log(`player tables -> ${path.relative(process.cwd(), OUT)}: ${exp.length} levels`);
