/** Original login art is keyed by element/gender, not by faction. Names recovered by matching PAK hashes. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { resolveAny } from './jx/hashindex.ts';
import { decodeSpr } from './jx/spr.ts';

export async function generateLoginFigures(): Promise<void> {
  const here = path.dirname(fileURLToPath(import.meta.url));
  const out = path.resolve(here, '../public/assets/ui/login/figures');
  fs.mkdirSync(out, { recursive: true });
  const meta: Record<string, { width: number; height: number; frames: number; columns: number; interval: number; idleWidth: number; idleHeight: number; anchorX: number; anchorY: number }> = {};
  for (const [series, chinese] of Object.entries({ kim: '金', moc: '木', thuy: '水', hoa: '火', tho: '土' })) {
    for (const [gender, sex] of Object.entries({ male: '男', female: '女' })) {
      // 0 = idle colour, 1 = selection action; use one shared crop to preserve position and scale.
      const poses = ['idle', 'action'].map((pose, index) => {
        const name = `\\spr\\ui3\\登入界面\\选存档人物\\角色_${chinese}_${sex}_${index}.spr`;
        const file = resolveAny(name);
        if (!file) throw new Error(`Missing original login figure: ${name}`);
        return { pose, spr: decodeSpr(fs.readFileSync(file)) };
      });
      // Ignore nearly transparent padding when finding a shared crop; keep the same crop for every frame.
      let left = Infinity, top = Infinity, right = -Infinity, bottom = -Infinity;
      for (const { spr } of poses) for (const f of spr.frames) for (let y = 0; y < f.h; y++) for (let x = 0; x < f.w; x++) {
        if (f.rgba[(y * f.w + x) * 4 + 3] < 100) continue;
        left = Math.min(left, f.x + x); top = Math.min(top, f.y + y);
        right = Math.max(right, f.x + x); bottom = Math.max(bottom, f.y + y);
      }
      if (!Number.isFinite(left)) throw new Error(`Empty login figure: ${series}-${gender}`);
      let idleLeft = Infinity, idleTop = Infinity, idleRight = -Infinity, idleBottom = -Infinity;
      for (const f of poses[0].spr.frames) for (let y = 0; y < f.h; y++) for (let x = 0; x < f.w; x++) {
        if (f.rgba[(y * f.w + x) * 4 + 3] < 100) continue;
        idleLeft = Math.min(idleLeft, f.x + x); idleTop = Math.min(idleTop, f.y + y);
        idleRight = Math.max(idleRight, f.x + x); idleBottom = Math.max(idleBottom, f.y + y);
      }
      left -= 2; top -= 2; right += 2; bottom += 2;
      const width = right - left + 1, height = bottom - top + 1;
      for (const { pose, spr } of poses) {
        const columns = Math.min(4, spr.frames.length), rows = Math.ceil(spr.frames.length / columns);
        const sheetWidth = width * columns, px = Buffer.alloc(sheetWidth * height * rows * 4);
        spr.frames.forEach((f, i) => {
          for (let y = 0; y < f.h; y++) for (let x = 0; x < f.w; x++) {
            const tx = f.x + x - left, ty = f.y + y - top;
            if (tx < 0 || tx >= width || ty < 0 || ty >= height) continue;
            const s = (y * f.w + x) * 4;
            const d = (((Math.floor(i / columns) * height + ty) * sheetWidth) + (i % columns) * width + tx) * 4;
            px.set(f.rgba.subarray(s, s + 4), d);
          }
        });
        const key = `${series}-${gender}-${pose}`;
        await sharp(px, { raw: { width: sheetWidth, height: height * rows, channels: 4 } })
          .webp({ lossless: true }).toFile(path.join(out, `${key}.webp`));
        // Some original files store 1 here; 1 ms is not a usable presentation rate. Use 80 ms for those.
        meta[key] = { width, height, frames: spr.frames.length, columns, interval: spr.interval > 1 ? spr.interval : 80,
          idleWidth: idleRight - idleLeft + 5, idleHeight: idleBottom - idleTop + 5,
          anchorX: (idleLeft + idleRight) / 2 - left, anchorY: idleBottom + 2 - top };
        console.log(`  login figure ${key}: ${width}x${height}, ${spr.frames.length} frames`);
      }
    }
  }
  fs.writeFileSync(path.resolve(here, '../src/art/login-figures.gen.ts'),
    '// Generated by gen:ui from original login SPR files. Do not edit.\n' +
    'export const LOGIN_FIGURES: Record<string, { width: number; height: number; frames: number; columns: number; interval: number; idleWidth: number; idleHeight: number; anchorX: number; anchorY: number }> = ' + JSON.stringify(meta, null, 2) + ';\n');
}
