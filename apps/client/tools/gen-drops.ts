/**
 * Original drop tables -> packages/shared/src/drops/drops.gen.ts (VT8).
 *
 *   npm run gen:drops -w @vltk/client
 *
 * Source: data_extract settings/droprate/**.ini (update01: npcdroprate10–90 by monster level band, boss/*, goldennpc/*).
 * [Main]: RandRange (denominator), MagicRate (1 in every table: blue lines on), MoneyRate (% per kill), MoneyScale,
 * Min/MaxItemLevel(+Scale) (item level from the monster level); [n]: Genre, Detail, Particular, RandRate (chance =
 * RandRate / RandRange per roll), Quality (1 = gold piece: Detail = goldequip row). Reading: docs/research/luck-drops.md.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { listGameFiles, readGameFile } from './jx/source.ts';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(HERE, '../../../packages/shared/src/drops/drops.gen.ts');

function ini(buf: Buffer): Record<string, Record<string, string>> {
  const out: Record<string, Record<string, string>> = {};
  let sec = '';
  for (const raw of new TextDecoder('gbk').decode(buf).split(/\r?\n/)) {
    const line = raw.replace(/;.*$/, '').trim();
    const m = /^\[(.+)\]$/.exec(line);
    if (m) { sec = m[1].trim(); out[sec] = {}; continue; }
    const eq = line.indexOf('=');
    if (eq > 0 && sec) out[sec][line.slice(0, eq).trim()] = line.slice(eq + 1).trim();
  }
  return out;
}

const files = listGameFiles('\\settings\\droprate\\').filter(f => /\.ini$/i.test(f));
const tables: Record<string, unknown> = {};
for (const f of files) {
  const t = ini(readGameFile(f));
  const m = t.Main;
  if (!m) continue;
  const n = (k: string) => Number(m[k]) || 0;
  const items: [number, number, number, number, number][] = [];
  for (let i = 1; i <= n('Count'); i++) {
    const r = t[String(i)];
    if (!r) continue;
    items.push([Number(r.Genre) || 0, Number(r.Detail) || 0, Number(r.Particular) || 0, Number(r.RandRate) || 0, Number(r.Quality) || 0]);
  }
  const key = f.replace(/^\\settings\\droprate\\/i, '').replace(/\.ini$/i, '').replace(/\\/g, '/');
  tables[key] = {
    range: n('RandRange'), magic: n('MagicRate'), moneyRate: n('MoneyRate'), moneyScale: n('MoneyScale'),
    minLevel: n('MinItemLevel'), minScale: n('MinItemLevelScale'), maxLevel: n('MaxItemLevel'), maxScale: n('MaxItemLevelScale'), items,
  };
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, `// Generated by apps/client/tools/gen-drops.ts from settings/droprate/**.ini. Do not edit by hand.
/* eslint-disable */

/** One original drop table (formulas/drops.ts reads it). */
export interface DropTable {
  /** RandRange: each roll draws 0…range−1 and walks the items' RandRate cumulatively (one item at most). */
  range: number;
  /** MagicRate (1 everywhere): blue lines are rolled. */
  magic: number;
  /** % chance of a money drop per kill, and its scale. */
  moneyRate: number;
  moneyScale: number;
  /** Item level from the monster level: lo = max(minLevel, ⌊L / minScale⌋), hi = min(maxLevel, ⌊L / maxScale⌋). */
  minLevel: number; minScale: number; maxLevel: number; maxScale: number;
  /** [Genre, Detail, Particular, RandRate, Quality] (Genre 0 = equipment: Detail = kind, Particular = type). */
  items: [number, number, number, number, number][];
}

export const DROP_TABLES: Record<string, DropTable> = ${JSON.stringify(tables, null, 0).replace(/\},"/g, '},\n  "')};
`);
console.log(`drops.gen.ts: ${Object.keys(tables).length} tables`);
