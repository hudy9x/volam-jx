import assert from 'node:assert/strict';
import { BOT_TRADE_RULES, CHAT, ITEMS, SHOP_ITEMS, MAGIC_ATTRIBS, botTradeReasons, botLootMessage, normalizeBotScenario, type Item } from '../packages/shared/src/index.js';
import { LootAnnouncer } from '../tools/bots/runner/LootAnnouncer.js';

const def = SHOP_ITEMS.smith.find(d => d.kind === 'melee' && d.level === 10)!;
const six: Item = { uid: 'new-drop', def: def.id, magic: [['a',1],['b',1],['c',1],['d',1],['e',1],['f',1]] };
assert.ok(botTradeReasons(six).includes('6 dòng'));
assert.equal(botLootMessage({ ...six, magic: six.magic!.slice(0,5) }, true), null);
assert.equal(botLootMessage({ uid:'p',def:'potion-2-5' }, true), null);
const rare = MAGIC_ATTRIBS.find(r => !r.prefix && r.kinds.includes(def.kind) && r.level <= def.level && (r.weights[def.kind] ?? 0)>0 && (r.weights[def.kind] ?? 0)<=BOT_TRADE_RULES.rareWeight)!;
assert.ok(rare, 'Need a real rare hidden option fixture');
const rareItem: Item = { uid:'rare',def:def.id,series:rare.series,magic:[[rare.attr,Math.max(1,rare.min),1]] };
assert.ok(botTradeReasons(rareItem).length);
assert.equal(botTradeReasons({ ...rareItem,magic:[[rare.attr,1]] }).length,0,'Rare prefixes alone must not trigger');
const large = MAGIC_ATTRIBS.find(r=>!r.prefix&&r.kinds.includes(def.kind)&&r.level===10&&r.max>0)!;
assert.ok(botTradeReasons({uid:'large',def:def.id,series:large.series,magic:[[large.attr,large.max,1]]}).length);
const announcer = new LootAnnouncer({chat:true,sell:true});
assert.equal(announcer.next(0,[six]),null,'Existing inventory must not be advertised');
announcer.pickedUp(six);announcer.pickedUp(six);
assert.match(announcer.next(0,[six])!,/^Rao bán/);
assert.equal(announcer.next(BOT_TRADE_RULES.botGapMs,[six]),null,'Duplicate events must not advertise twice');
const next={...six,uid:'next'};announcer.pickedUp(next);
assert.equal(announcer.next(1,[next]),null);
assert.ok(announcer.next(BOT_TRADE_RULES.botGapMs,[next]));
const gone={...six,uid:'sold'};announcer.pickedUp(gone);
assert.equal(announcer.next(BOT_TRADE_RULES.botGapMs*2,[]),null,'Do not advertise an item no longer carried');
const chat=new LootAnnouncer({chat:true,sell:false});chat.pickedUp(six);assert.match(chat.next(0,[six])!,/^Vừa nhặt/);
assert.ok(botLootMessage(six,true)!.length<=CHAT.maxLength);
const old=normalizeBotScenario({duration:1,behaviors:{pk:100}});assert.equal(old.duration,0);assert.equal(old.activities.grind,true);
const sc=normalizeBotScenario({activities:{grind:false,chat:true,sell:false,autoAcceptTeam:false}});assert.deepEqual(sc.activities,{grind:false,chat:true,sell:false,autoAcceptTeam:false});
console.log('PASS: six lines/rare or large hidden options, only fresh loot, dedupe, cooldown, absent items, chat vs sell, indefinite scenario migration');
assert.equal(normalizeBotScenario({}).joinPerSecond,3);
assert.equal(normalizeBotScenario({joinPerSecond:1}).joinPerSecond,3);
assert.equal(normalizeBotScenario({joinPerSecond:999}).joinPerSecond,5);
assert.equal(normalizeBotScenario({joinPerSecond:4}).joinPerSecond,4);
console.log('PASS: staggered join setting is bounded to 3–5 bots/s, default 3');

const gold = Object.values(ITEMS).find(d=>d.gold && d.gold.lines.length===2 && d.gold.lines[1][2][0]>0)!;
assert.ok(gold);
assert.ok(botTradeReasons({uid:'gold-hidden',def:gold.id,magic:[[gold.gold!.lines[0][0],gold.gold!.lines[0][2][0]],[gold.gold!.lines[1][0],gold.gold!.lines[1][2][0],1]]}).length,'Gold hidden maxima must use their own row, even with fewer than six lines');
